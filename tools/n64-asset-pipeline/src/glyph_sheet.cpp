/**
 * glyph_sheet.cpp
 *
 * Builds a 128x128 RGBA5551 glyph sheet for N64 text rendering.
 *
 * Layout: 16 glyphs per row × 16 rows = 256 glyphs, each 8×8 pixels.
 * Glyph index = ASCII code point (0-255).
 *
 * This implementation generates a built-in pixel font (based on the
 * classic PC-8 / IBM CGA 8×8 font) rather than requiring a TTF file,
 * keeping the tool self-contained.
 *
 * The glyphs cover all printable ASCII (0x20-0x7E) plus common Latin-1
 * extended characters (0xA0-0xFF) for Wesnoth's translated content.
 */

