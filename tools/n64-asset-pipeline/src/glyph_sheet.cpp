static uint8_t k_font_8x8[256][8];
static void init_font() {
    static bool done = false;
    if (done) return;
    done = true;
    for (const auto& g : k_font_src)
        std::memcpy(k_font_8x8[g.code], g.rows, 8);
}

// -----------------------------------------------------------------------
// build_glyph_sheet
// -----------------------------------------------------------------------
Texture16 build_glyph_sheet(const std::filesystem::path& /*ttf_path*/) {
    // Sheet is 128x128, 8x8 glyphs, 16 glyphs per row, 16 rows = 256 glyphs
    constexpr int SHEET_W = 128;
    constexpr int SHEET_H = 128;
    constexpr int GLYPH_W = 8;
    constexpr int GLYPH_H = 8;
    constexpr int COLS = 16;

    init_font();
    Texture16 sheet;
    sheet.width  = SHEET_W;
    sheet.height = SHEET_H;
    sheet.pixels.resize(SHEET_W * SHEET_H, 0x0001); // transparent black

    for (int glyph = 0; glyph < 256; ++glyph) {
        int col = glyph % COLS;
        int row = glyph / COLS;
        int ox  = col * GLYPH_W;
        int oy  = row * GLYPH_H;

        for (int py = 0; py < GLYPH_H; ++py) {
            uint8_t bits = k_font_8x8[glyph][py];
            for (int px = 0; px < GLYPH_W; ++px) {
                bool lit = (bits >> (7 - px)) & 1;
                // White pixel (fully opaque) or transparent
                sheet.pixels[(oy + py) * SHEET_W + (ox + px)] =
                    lit ? 0xFFFF : 0x0000; // RGBA5551: white=0xFFFF, transparent=0x0000
            }
        }
    }

    return sheet;
}

